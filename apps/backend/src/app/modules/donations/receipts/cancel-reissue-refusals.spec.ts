/**
 * Regression coverage for the cancel/reissue state machine in `DonationReceiptsController`
 * (apps/backend/src/app/modules/donations/receipts/controller.ts, `cancelReceipt` /
 * `reissueReceipt`), added following a production-risk review that flagged these refusal paths
 * as untested. The blast radius of a bug here is a statement — a donor's unnumbered whole-year
 * summary — getting "reissued" into a serialized (numbered) document, or a numbered document's
 * serial being reused/gapped.
 *
 * State machine as read from the source (kind: 'per_gift' | 'cumulative' | 'acknowledgement' |
 * 'statement'; status: 'issued' | 'cancelled'):
 *
 * cancelReceipt(receiptId, reason):
 *   - receipt not found (including wrong tenant, since getReceiptById is tenant-scoped) -> NotFoundError
 *   - kind === 'statement'                                    -> BadRequestError (never cancelled one-by-one)
 *   - status !== 'issued' (already cancelled)                 -> ConflictError
 *   - else: sets status='cancelled', cancelled_reason/at/by, reissue_required=false
 *
 * reissueReceipt(receiptId, reason?):
 *   - predecessor not found (including wrong tenant)           -> NotFoundError
 *   - kind === 'statement'                                     -> BadRequestError (regenerated by year-end rerun, not reissued)
 *   - kind === 'acknowledgement'                                -> BadRequestError (not reissued at all)
 *   - status === 'issued' && no reason given                    -> BadRequestError
 *   - workspace regime !== predecessor's frozen regime           -> PreconditionFailedError
 *   - every covered gift refunded (surviving.length === 0)       -> PreconditionFailedError
 *   - donor has no resolvable mailing address                    -> PreconditionFailedError
 *   - predecessor's frozen advantage_cents >= surviving amount    -> PreconditionFailedError
 *   - else: transaction takes a NEW serial from the counter, cancels the predecessor (if still
 *     'issued') or clears its reissue_required flag (if already cancelled), inserts a successor
 *     row with replaces_receipt_id = predecessor.id.
 *
 * Reissue's validation runs entirely before `nextSerial` is called inside the transaction, so a
 * refused reissue must never advance/reuse the receipt_counters sequence — pinned below.
 */

// Reissue commits real transactions against the shared receipt_counters row (the counter lock IS
// part of what several tests here pin), so this file takes the same lock the sibling
// controller.spec.ts does and the two take turns.
useExclusiveDbLock(DB_TEST_LOCKS.RECEIPT_COUNTERS);

const rand = () => String(Math.floor(Math.random() * 100000000) + 1000000);

async function cleanTenant(db: any, tenantId: string) {
  await db
    .updateTable('tenants')
    .set({ admin_id: null, createdby_id: null, placeholder_household_id: null })
    .where('id', '=', tenantId)
    .execute();
  for (const table of [
    'background_jobs',
    'donation_receipt_items',
    'donation_receipts',
    'files',
    'receipt_counters',
    'receipt_statement_runs',
    'donations',
    'settings',
    'persons',
    'households',
    'campaigns',
    'user_activity',
    'authusers',
  ]) {
    await db.deleteFrom(table).where('tenant_id', '=', tenantId).execute();
  }
  await db.deleteFrom('tenants').where('id', '=', tenantId).execute();
}

/** CRA-complete receipts.* settings; individual tests unset/override keys to exercise guards. */
async function seedReceiptSettings(db: any, tenantId: string, userId: string, overrides: Record<string, unknown> = {}) {
  const values: Record<string, unknown> = {
    'receipts.regime': 'cra_charity',
    'receipts.mode': 'per_gift',
    'receipts.org_legal_name': 'Test Charity',
    'receipts.org_address': '1 Test Way, Ottawa, ON',
    'receipts.registration_number': '123456789 RR 0001',
    'receipts.place_of_issue': 'Ottawa',
    'receipts.signatory_name': 'Pat Signer',
    'receipts.signature_file_id': '1',
    'receipts.number_prefix': 'T',
    ...overrides,
  };
  await db
    .insertInto('settings')
    .values(
      Object.entries(values)
        .filter(([, v]) => v !== undefined)
        .map(([key, value]) => ({
          tenant_id: tenantId,
          key,
          value: JSON.stringify(value),
          createdby_id: userId,
          updatedby_id: userId,
        })),
    )
    .execute();
}

/** Upsert a single receipts.* setting key without touching the others already seeded. */
async function setSetting(db: any, tenantId: string, userId: string, key: string, value: unknown) {
  await db.deleteFrom('settings').where('tenant_id', '=', tenantId).where('key', '=', key).execute();
  await db
    .insertInto('settings')
    .values({
      tenant_id: tenantId,
      key,
      value: JSON.stringify(value),
      createdby_id: userId,
      updatedby_id: userId,
    })
    .execute();
}

